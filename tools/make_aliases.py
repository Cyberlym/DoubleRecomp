#!/usr/bin/env python3
"""Generate x86_aliases.cpp: one weak alias per recompiled function, from an exports.def.

On Windows, /alternatename resolves `sub_XXXX` to `__imp__sub_XXXX` at link time unless a host
override defines it strongly. On ELF the equivalent is a weak definition in a translation unit of
its own, so no caller shares a TU with the alias (that would bind calls at compile time and
defeat overrides)."""
import re
import sys


def main(exports_def, out_cpp):
    names = []
    with open(exports_def) as f:
        for line in f:
            m = re.match(r"\s+(__imp__\S+)\s*$", line)
            if m:
                names.append(m.group(1))
    with open(out_cpp, "w") as f:
        f.write("// generated by make_aliases.py from exports.def - do not edit\n")
        f.write('#include "cpu/x86_ops.h"\n\n')
        for n in names:
            f.write(f'extern "C" void {n}(X86Context& __restrict ctx, uint8_t* base);\n')
        f.write("\n")
        for n in names:
            f.write(f"X86_WEAK_FUNC({n[7:]}, {n})\n")
    print(f"{len(names)} aliases")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
